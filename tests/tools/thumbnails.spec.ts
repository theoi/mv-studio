import { createHash } from 'node:crypto'
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { openHarness, test } from '../e2e/fixtures.ts'

// Renders a thumbnail of every built-in plugin, look and text style from its preview project (src/plugins/preview.ts)
// into public/thumbnails/<kind>/<id>.webp and writes src/plugins/thumbnails.manifest.ts. Run `npm run build &&
// npm run thumbnails` after adding or changing a library item, then rebuild.
const OUT = path.resolve('public/thumbnails')
const MANIFEST = path.resolve('src/plugins/thumbnails.manifest.ts')
const KINDS = ['effect', 'transition', 'generator', 'text-animation', 'look', 'text-style'] as const

test('library thumbnails', async ({ page }) => {
  page.on('console', (m) => {
    if (m.type() === 'error' || m.type() === 'warning') console.warn(m.text())
  })
  await openHarness(page)
  const manifest: Record<string, Record<string, string>> = {}
  for (const kind of KINDS) {
    const items: { id: string; data: string }[] = await page.evaluate(async (kind) => {
      const { engine, media, plugins, testing } = window.mvStudio
      const { THUMBNAIL_WIDTH: W, THUMBNAIL_HEIGHT: H } = plugins.thumbnails
      const store = async (mode: 'color' | 'depth') =>
        media.mediaStore.storeBlob(await plugins.preview.sampleSceneBlob(1280, 720, mode), {
          kind: 'image',
          name: `scene-${mode}.png`,
          origin: { type: 'generated' },
        })
      const options = { image: await store('color'), depth: await store('depth') }
      const ids: string[] =
        kind === 'look'
          ? plugins.looks.lookRegistry.list().map((l: { id: string }) => l.id)
          : kind === 'text-style'
            ? plugins.typography.styles.TEXT_STYLES.map((s: { id: string }) => s.id)
            : engine.pluginRegistry.list(kind).map((d: { id: string }) => d.id)
      // Rendered at twice the size and scaled down, for smooth edges on text and fine shader detail.
      const { compositor } = testing.createCompositor('export', W * 2, H * 2)
      const out = new OffscreenCanvas(W, H)
      const ctx = out.getContext('2d')!
      ctx.imageSmoothingQuality = 'high'
      const result: { id: string; data: string }[] = []
      for (const id of ids) {
        const { project, time } =
          kind === 'look'
            ? plugins.preview.lookPreview(id, options)
            : kind === 'text-style'
              ? plugins.preview.textStylePreview(id, options)
              : plugins.preview.pluginPreview(id, options)
        await compositor.render(project, time)
        ctx.clearRect(0, 0, W, H)
        ctx.drawImage(compositor.canvas, 0, 0, W, H)
        const blob = await out.convertToBlob({ type: 'image/webp', quality: 0.82 })
        const bytes = new Uint8Array(await blob.arrayBuffer())
        let s = ''
        for (let i = 0; i < bytes.length; i += 0x8000)
          s += String.fromCharCode(...bytes.subarray(i, i + 0x8000))
        result.push({ id, data: btoa(s) })
      }
      compositor.dispose()
      return result
    }, kind)
    const dir = path.join(OUT, kind)
    rmSync(dir, { recursive: true, force: true })
    mkdirSync(dir, { recursive: true })
    const hashes: Record<string, string> = {}
    for (const item of items) {
      const bytes = Buffer.from(item.data, 'base64')
      writeFileSync(path.join(dir, `${item.id}.webp`), bytes)
      hashes[item.id] = createHash('sha256').update(bytes).digest('hex').slice(0, 10)
    }
    manifest[kind] = hashes
    console.warn(`${kind}: ${items.length} thumbnails`)
  }
  writeFileSync(
    MANIFEST,
    '// Generated by tests/tools/thumbnails.spec.ts (npm run thumbnails): kind -> id -> content hash. Do not edit by hand.\n' +
      `export const THUMBNAILS: Record<string, Record<string, string>> = ${JSON.stringify(manifest, null, 2)}\n`,
  )
})
